import { access, readFile } from 'node:fs/promises';
import { join } from 'node:path';
const mustExist = async path => { await access(path); };
await mustExist('dist/index.html');
await mustExist('dist/manifest.webmanifest');
await mustExist('dist/sw.js');
const html = await readFile('dist/index.html', 'utf8');
const appSource = await readFile('public/app.js', 'utf8');
if (/FOMS|supabase/i.test(appSource)) throw new Error('Production app references a non Focus Space backend.');
const manifest = JSON.parse(await readFile('dist/manifest.webmanifest', 'utf8'));
if (!html.includes('Focus Space')) throw new Error('dist/index.html is not the Focus Space entry.');
if (manifest.start_url !== '/') throw new Error('PWA start_url must be /.');
if (manifest.display !== 'standalone') throw new Error('PWA display must be standalone.');
const refs = [...html.matchAll(/(?:src|href)="([^"#]+)"/g)].map(match => match[1]).filter(ref => ref.startsWith('/assets/') || ref.startsWith('./assets/'));
for (const ref of refs) await mustExist(join('dist', ref.replace(/^\.\//, '').replace(/^\//, '')));
for (const asset of ['manifest.webmanifest', 'sw.js', 'assets/warm-study.svg', 'assets/deep-work.svg', 'assets/reading-room.svg', 'assets/rainy-retreat.svg', 'assets/morning-planning.svg']) await mustExist(join('dist', asset));
const sw = await readFile('dist/sw.js', 'utf8');
if (!sw.includes('/index.html') || !sw.includes('/manifest.webmanifest')) throw new Error('Service worker core cache is incomplete.');
console.log('deployment checks: dist, Vite assets, PWA shell, and scene assets passed');
